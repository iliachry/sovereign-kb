"""Soar-to-Python Compiler (`soarc`): Transpiles `.soar` productions into standalone executable Python code."""

from __future__ import annotations

from typing import Any

from .ast_nodes import (
    ConjunctiveTest,
    DisjunctionTest,
    EqualityTest,
    Production,
    RelationalTest,
    RHSFunctionStandalone,
    Test,
)
from .kernel import SoarKernel
from .parser import parse_soar


def _safe_comment(text: str) -> str:
    return text.replace("\r", " ").replace("\n", "\\n")


class SoarToPythonTranspiler:
    """Compiles `.soar` AST into a standalone, executable Python module."""

    def transpile(self, soar_source: str, class_name: str = "CompiledSoarAgent") -> str:
        productions = parse_soar(soar_source)
        lines: list[str] = [
            '"""Auto-generated by Soar-to-Python Compiler (soarc)."""',
            "",
            "from __future__ import annotations",
            "from typing import Any",
            "from sovereign_kb.soar.kernel import SoarKernel",
            "",
            "",
            f"class {class_name}:",
            '    """Standalone compiled Soar cognitive agent."""',
            "",
            f"    SOAR_SOURCE: str = {soar_source!r}",
            "",
            "    def __init__(self, enable_chunking: bool = True) -> None:",
            "        self.kernel = SoarKernel(enable_chunking=enable_chunking)",
            "        self.kernel.load_soar_code(self.SOAR_SOURCE)",
            "",
            "    def step_cycle(self) -> dict[str, Any]:",
            "        return self.kernel.step_cycle()",
            "",
            "    def run_to_completion(self, max_cycles: int = 35) -> dict[str, Any]:",
            "        return self.kernel.run_to_completion(max_cycles=max_cycles)",
            "",
        ]

        rule_methods: list[str] = []
        for idx, prod in enumerate(productions):
            safe_name = f"rule_{idx:02d}_" + "".join(ch if ch.isalnum() else "_" for ch in prod.name)
            rule_methods.append(safe_name)
            lines.extend(self._emit_production_method(safe_name, prod))
            lines.append("")

        lines.extend(
            [
                "    def production_manifest(self) -> list[dict[str, Any]]:",
                "        return [",
            ]
        )
        for idx, prod in enumerate(productions):
            lines.append(
                f"            {{'index': {idx}, 'name': {prod.name!r}, 'conditions': {len(prod.conditions)}, 'actions': {len(prod.actions)}, 'is_chunk': {prod.is_chunk!r}}},"
            )
        lines.extend(
            [
                "        ]",
                "",
                "    def list_rule_handlers(self) -> list[str]:",
                f"        return {rule_methods!r}",
                "",
            ]
        )
        return "\n".join(lines)

    def _emit_production_method(self, method_name: str, prod: Production) -> list[str]:
        doc = prod.doc or f"Compiled from Soar production `{prod.name}`"
        out = [
            f"    def {method_name}(self, bindings: dict[str, Any] | None = None) -> dict[str, Any]:",
            f"        {doc!r}",
            f"        # LHS Conditions ({len(prod.conditions)} patterns)",
        ]
        for c_idx, cond in enumerate(prod.conditions):
            neg = "NOT " if cond.negated else ""
            state_lbl = "state " if cond.is_state else ""
            attrs_desc = ", ".join(
                f"{'-' if at.negated else ''}^{_safe_comment(str(at.attr))} {_safe_comment(self._describe_test(at.value_test))}"
                for at in cond.attr_tests
            )
            out.append(f"        # C{c_idx + 1}: {neg}({state_lbl}<{cond.id_var.name}> {attrs_desc})")

        out.append("        # RHS Actions")
        for act in prod.actions:
            if isinstance(act, RHSFunctionStandalone):
                out.append(f"        # Call: ({_safe_comment(act.call.func_name)} ...)")
            else:
                prefs = " ".join(p.pref_type for p in act.preferences)
                out.append(
                    f"        # Assert: ({_safe_comment(str(act.id_sym))} ^{_safe_comment(str(act.attr))} {_safe_comment(str(act.value))} {prefs})"
                )

        out.append(f"        prod_obj = self.kernel.productions[{prod.name!r}]")
        out.append("        matches = self.kernel.match_production(prod_obj)")
        out.append(
            f"        return {{'production': {prod.name!r}, 'is_chunk': {prod.is_chunk!r}, 'active_matches': len(matches), 'bindings': dict(bindings or {{}})}}"
        )
        return out

    def _describe_test(self, t: Test) -> str:
        if isinstance(t, EqualityTest):
            return repr(t.target)
        if isinstance(t, RelationalTest):
            return f"{t.op} {t.target!r}"
        if isinstance(t, DisjunctionTest):
            return f"<< {' '.join(map(str, t.options))} >>"
        if isinstance(t, ConjunctiveTest):
            return "{ " + " ".join(self._describe_test(s) for s in t.tests) + " }"
        return str(t)


def transpile_soar_to_python(soar_source: str, class_name: str = "CompiledSoarAgent") -> dict[str, Any]:
    """Transpile `.soar` source into Python code and verify it compiles, instantiates, and executes cleanly."""
    transpiler = SoarToPythonTranspiler()
    python_code = transpiler.transpile(soar_source, class_name=class_name)

    ns: dict[str, Any] = {"SoarKernel": SoarKernel}
    compiled_obj = compile(python_code, "<soarc_transpiled>", "exec")
    exec(compiled_obj, ns)
    agent_cls = ns[class_name]
    instance = agent_cls()
    manifest = instance.production_manifest()
    handlers = instance.list_rule_handlers()

    verified = True
    verification_error: str | None = None
    try:
        probe_agent = agent_cls()
        probe_agent.step_cycle()
    except Exception as exc:
        verified = False
        verification_error = f"{type(exc).__name__}: {exc}"

    return {
        "class_name": class_name,
        "python_code": python_code,
        "line_count": len(python_code.splitlines()),
        "rule_count": len(manifest),
        "manifest": manifest,
        "handlers": handlers,
        "verified": verified,
        "verification_error": verification_error,
    }
